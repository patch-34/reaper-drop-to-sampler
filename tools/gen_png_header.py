#!/usr/bin/env python3
"""Embed overlay PNGs as byte arrays for macOS (Windows uses RCDATA in resource.rc)."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
out = ["// Generated by tools/gen_png_header.py — do not edit.", "#pragma once", ""]
for name in ("sampler_insert", "sampler_replace"):
    data = (root / "src" / "res" / f"{name}.png").read_bytes()
    out.append(f"static const unsigned char k_{name}_png[{len(data)}] = {{")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+16]) + ",")
    out.append("};")
    out.append("")
(root / "src" / "res" / "overlay_png.h").write_text("\n".join(out))
